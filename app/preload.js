'use strict';
const {contextBridge,ipcRenderer} = require('electron');
if (process.isMainFrame) contextBridge.exposeInMainWorld('desktop', {
  theme:process.argv.includes('--draftelio-theme=dark')?'dark':'light',
  setTheme:value=>ipcRenderer.invoke('interface:theme',value),
  design:value=>ipcRenderer.invoke('interface:design',value),
  state:()=>ipcRenderer.invoke('project:state'),
  projects:()=>ipcRenderer.invoke('project:list'),
  switchProject:root=>ipcRenderer.invoke('project:switch',root),
  canGoHome:()=>ipcRenderer.invoke('project:home'),
  customBlocks:()=>ipcRenderer.invoke('blocks:list'),
  saveBlock:data=>ipcRenderer.invoke('blocks:save',data),
  deleteBlock:id=>ipcRenderer.invoke('blocks:delete',id),
  open:()=>ipcRenderer.invoke('project:open'),
  create:()=>ipcRenderer.invoke('project:create'),
  save:data=>ipcRenderer.invoke('project:save',data),
  newPage:name=>ipcRenderer.invoke('project:new-page',name),
  importImage:()=>ipcRenderer.invoke('project:image'),
  export:()=>ipcRenderer.invoke('project:export'),
  reveal:()=>ipcRenderer.invoke('project:reveal'),
  aiCatalog:()=>ipcRenderer.invoke('ai:catalog'),
  aiHistory:()=>ipcRenderer.invoke('ai:history'),
  aiSettings:data=>ipcRenderer.invoke('ai:settings',data),
  aiStatus:provider=>ipcRenderer.invoke('ai:status',provider),
  aiLogin:provider=>ipcRenderer.invoke('ai:login',provider),
  aiExecutable:provider=>ipcRenderer.invoke('ai:executable',provider),
  aiGenerate:data=>ipcRenderer.invoke('ai:generate',data),
  aiCancel:()=>ipcRenderer.invoke('ai:cancel'),
  aiLoginCode:code=>ipcRenderer.invoke('ai:login-code',code),
  aiImportPlugin:()=>ipcRenderer.invoke('ai:import-plugin'),
  aiRevealPlugins:()=>ipcRenderer.invoke('ai:reveal-plugins'),
  onAiEvent:callback=>ipcRenderer.on('ai:event',(_event,event)=>callback(event)),
  dirty:value=>ipcRenderer.send('project:dirty',value === true),
  onCommand:callback=>ipcRenderer.on('editor:command',(_event,command)=>callback(command))
});
